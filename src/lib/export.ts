import type { Framework, JiraEdition, Metric, Role } from '../types/index.ts';
import { metricsByCategory, metricsForRole } from './browse.ts';
import { CATEGORY_LABELS, FRAMEWORK_LABELS, MANDATE_LABELS } from './labels.ts';
import { mandateSummary } from './mandates.ts';
import { substitutePlaceholders, type PlaceholderValues } from './placeholders.ts';

/** RFC 4180 style: quote a field if it contains a comma, quote or line break. */
export function csvField(value: string): string {
  return /[",\r\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

const csvRow = (fields: string[]) => fields.map(csvField).join(',');

/**
 * The mandate matrix as CSV: one row per metric, one column per role. Cells
 * where the level differs by framework list each framework.
 */
export function matrixCsv(metrics: Metric[], roles: Role[], framework?: Framework): string {
  const header = [
    'Metric (proposed baseline mandate levels)',
    'Category',
    'Frameworks',
    ...roles.map((r) => r.name),
  ];
  const rows = metricsByCategory(metrics, framework).flatMap((group) =>
    group.metrics.map((metric) => [
      metric.name,
      CATEGORY_LABELS[group.category],
      metric.framework.map((f) => FRAMEWORK_LABELS[f]).join('; '),
      ...roles.map((role) => {
        const summary = mandateSummary(metric, role.id, framework);
        return summary.varies
          ? summary.perFramework
              .map((e) => `${MANDATE_LABELS[e.mandate]} (${FRAMEWORK_LABELS[e.framework]})`)
              .join('; ')
          : MANDATE_LABELS[summary.mandate];
      }),
    ]),
  );
  // CRLF line endings and a leading BOM help spreadsheet apps read UTF-8 correctly.
  return '﻿' + [header, ...rows].map(csvRow).join('\r\n') + '\r\n';
}

const EDITION_NAMES: Record<JiraEdition, string> = {
  datacenter: 'Jira Data Center',
  cloud: 'Jira Cloud',
};

/**
 * All JQL for a role's mandatory, recommended and optional metrics, for one
 * edition, as plain text. Filled placeholder values are substituted.
 */
export function roleJqlText(options: {
  metrics: Metric[];
  role: Role;
  edition: JiraEdition;
  framework?: Framework;
  values: PlaceholderValues;
  generatedOn: string;
}): string {
  const { metrics, role, edition, framework, values, generatedOn } = options;
  const groups = metricsForRole(metrics, role.id, framework);
  const lines: string[] = [
    `JQL for ${role.name} — ${EDITION_NAMES[edition]}`,
    framework ? `Framework: ${FRAMEWORK_LABELS[framework]}` : 'Framework: all',
    `Generated by Jira Metrics Hub on ${generatedOn}.`,
    '',
    'Mandate levels are a PROPOSED BASELINE; your organisation decides.',
    'JQL returns lists and counts. For metrics marked "number comes from", the query only',
    'selects the issues; the number comes from the report, gadget or calculation named.',
    'Queries marked NEEDS VERIFICATION could not be fully confirmed from official docs.',
    'Unfilled placeholders are left as {{NAME}}.',
  ];

  for (const mandate of ['mandatory', 'recommended', 'optional'] as const) {
    const items = groups[mandate];
    lines.push(
      '',
      '='.repeat(72),
      `${MANDATE_LABELS[mandate].toUpperCase()} (${items.length})`,
      '='.repeat(72),
    );
    for (const { metric } of items) {
      const variants = metric.jql.filter((v) => v.edition === edition || v.edition === 'both');
      lines.push('', `## ${metric.name}`);
      if (metric.calcMethod !== 'jql-count') {
        lines.push(`Number comes from: ${metric.calcMethod.replace(/-/g, ' ')}`);
      }
      if (variants.length === 0) {
        lines.push(
          metric.jql.length === 0
            ? '(No JQL applies to this metric.)'
            : `(No ${EDITION_NAMES[edition]} query.)`,
        );
        continue;
      }
      for (const v of variants) {
        const flags = [
          v.verification === 'needs-verification' ? 'NEEDS VERIFICATION' : '',
          v.requiresApp ? `REQUIRES ${v.requiresApp}` : '',
        ].filter(Boolean);
        lines.push(`- ${v.label}${flags.length ? ` [${flags.join('; ')}]` : ''}`);
        lines.push(`  ${substitutePlaceholders(v.jql, values)}`);
        if (v.notes) lines.push(`  Note: ${v.notes}`);
      }
    }
  }
  return lines.join('\r\n') + '\r\n';
}

/** Saves text as a file in the browser. Nothing leaves the user's machine. */
export function downloadText(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

/** Today's date as YYYY-MM-DD in the user's time zone. */
export function today(): string {
  const d = new Date();
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}
